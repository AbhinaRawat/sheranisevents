                                  It is not just an upgrade in academic difficulty. It is an upgrade in everything - in
                                  independence, in identity, in the sheer variety of experiences available to a young person
                                  suddenly surrounded by hundreds of peers with different backgrounds, interests, and ideas.
                                </p>
