                                    <h3>FAQ: CBCI Education MasterMinds – Your Questions Answered</h3>
                                
                                    <p><strong>Q: Who can participate in CBCI Education MasterMinds?</strong></p>
                                    <p>
                                      Students of Catholic schools across India are eligible. The programme covers multiple age groups and
                                      activity categories, ensuring relevance for students at different levels of schooling.
                                    </p>
                                
                                    <p><strong>Q: Is this programme only about quizzing?</strong></p>
                                    <p>
                                      Not at all. While the quiz is central to the programme, students can also participate in singing,
                                      dancing, drawing, and elocution – making it a true all-round talent hunt.
                                    </p>
                                
                                    <p><strong>Q: How is the competition conducted?</strong></p>
                                    <p>
                                      The programme uses a combination of online assessments, OMR sheet-based tests, and live events – a
                                      hybrid format designed for maximum inclusivity across all regions of India.
                                    </p>
                                
                                    <p><strong>Q: What topics does the quiz cover?</strong></p>
                                    <p>
                                      Questions span general knowledge, current affairs, constitutional values, social justice, media
                                      literacy, and moral reasoning. The focus is on broad awareness and critical thinking rather than
                                      rote recall.
                                    </p>
                                
                                    <p><strong>Q: How often is this held, and when?</strong></p>
                                    <p>
                                      CBCI Education MasterMinds is held every year, timed around Children's Day on November 14th, making
                                      it an annual milestone for participating schools.
                                    </p> 
