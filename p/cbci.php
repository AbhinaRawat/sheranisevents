                                <p>
                                  Ask any student about their most memorable school moment, and chances are it was not a classroom lecture.
                                  It was the rush of stepping onto a stage, the nervous excitement before a quiz round, or the roar of
                                  applause after a performance they had rehearsed for weeks. School competitions have a way of shaping
                                  young people that textbooks simply cannot replicate.
                                </p>
                                <p>
                                  Yet, across India, countless talented children never get that moment. Either their school does not host
                                  enough platforms, or the competitions available are too narrow, limited to academics only, leaving the
                                  dancer, the debater, and the artist unrecognised.
                                </p>
                                <p>
                                  At Sheranis Events, we understand the power of a well-organised, inclusive event. That is why we are
                                  proud to be associated with a programme that is changing the game for school students nationwide –
                                  CBCI Education MasterMinds.
                                </p>
                            
                                <hr />
                            
                                <h3>CBCI Education MasterMinds: The Programme</h3>
                                <p>
                                  CBCI Education MasterMinds is India's most comprehensive and most inclusive quiz-based movement for
                                  school students to date. Conceived and catalysed by the CBCI Office for Education and Culture, this
                                  mega-campaign is not just a competition – it is a nationwide knowledge and talent movement that gives
                                  every child a stage, a spotlight, and a purpose.
                                </p>
                                <p>
                                  From general awareness and constitutional values to social justice and media literacy, the programme
                                  integrates learning with lived experience in a way that very few school competitions in India have
                                  attempted before.
                                </p>
                            
                                <hr />
                            
                                <h3>The Mission: Building Globally Ready, Value-Rooted Students</h3>
                                <p>
                                  Today's competitive world demands more from young students than ever before. They are expected to think
                                  critically, speak confidently, stay informed, and carry strong values – all at the same time. Keeping
                                  this reality in mind, the CBCI Office for Education and Culture created a platform that addresses each
                                  of these needs directly.
                                </p>
                                <p>
                                  The mission of CBCI Education MasterMinds is clear: to offer direction to students of Catholic schools
                                  across India by giving them a space to perform, compete, discover, and grow. The programme integrates
                                  messaging designed to:
                                </p>
                                <ul>
                                  <li>Sensitise students to the importance of constitutional values</li>
                                  <li>Encourage moral uprightness and value-based convictions</li>
                                  <li>Build critical understanding of social justice issues</li>
                                  <li>Promote awareness around media, cultural values, and political systems</li>
                                  <li>Strengthen general knowledge and current affairs understanding</li>
                                </ul>
                                <p>
                                  This is not a competition built on pressure. It is a platform built on belief – the belief that every
                                  child carries something extraordinary, and that the right opportunity can bring it to light.
                                </p>
                            
                                <hr />
                            
                                <h3>The Headliner: Quizmaster Adittya Nath Mubayi</h3>
                                <p>
                                  Every great event has a face that defines it. For CBCI Education MasterMinds, that face belongs to
                                  Adittya Nath Mubayi, one of India's most respected and passionate quizmasters, who brings decades of
                                  expertise to this programme.
                                </p>
                                <p>
                                  His involvement ensures that the quiz content is not only intellectually rigorous but also engaging,
                                  age-appropriate, and genuinely exciting for young participants. A great quizmaster does not just read
                                  questions – he creates an atmosphere where curiosity feels rewarding and knowledge feels like power.
                                  That is precisely what Adittya Nath Mubayi brings to every edition of this programme.
                                </p>
                                <p>
                                  For students who have grown up watching quiz shows on television, the experience of competing under
                                  the guidance of a quizmaster of this calibre is nothing short of electrifying.
                                </p>
                            
                                <hr />
                            
                                <h3>A Stage for Every Talent: What Students Can Participate In</h3>
                                <p>
                                  One of the most remarkable aspects of CBCI Education MasterMinds is how wide it casts its net. The
                                  programme recognises that talent is not one-dimensional, and neither are children. Students can
                                  showcase their abilities across a rich range of activities, including:
                                </p>
                                <ul>
                                  <li><strong>Quiz Competition</strong> – General awareness, GK, current affairs, constitutional values, and social issues</li>
                                  <li><strong>Singing</strong> – Vocal performances on a national platform</li>
                                  <li><strong>Dancing</strong> – Cultural expression and creative movement</li>
                                  <li><strong>Drawing</strong> – Visual imagination and artistic storytelling</li>
                                  <li><strong>Elocution</strong> – Public speaking, debate, and confident articulation</li>
                                  <li><strong>And more creative categories</strong> – added and refined each year</li>
                                </ul>
                                <p>
                                  This multi-activity structure means that a child who may not be a quiz champion could still walk away
                                  as a celebrated performer or a confident speaker. The programme sees the whole child – not just the
                                  academic one. For many students, this is their first experience of a national-level stage. That
                                  experience stays with them long after the event ends.
                                </p>
                            
                                <hr />
                            
                                <h3>Behind the Programme: The Partners Who Make It Possible</h3>
                                <p>
                                  A movement of this scale does not come together by accident. CBCI Education MasterMinds is built on a
                                  foundation of strong institutional partnerships and deep professional expertise.
                                </p>
                                <ul>
                                  <li>
                                    <strong>The CBCI Office for Education and Culture</strong> – The driving force behind the entire
                                    initiative, this office has a long-standing legacy of promoting quality, values-based education
                                    across India. Their commitment to the holistic development of students gives this programme its soul.
                                  </li>
                                  <li>
                                    <strong>Franciscan Solutions Pvt. Ltd.</strong> – As an ISO 9001:2015 Certified Multinational
                                    Ed-Tech Company, Franciscan Solutions brings the operational infrastructure, technology backbone,
                                    and execution capability required to run a programme at this scale – fairly, seamlessly, and
                                    inclusively across the country.
                                  </li>
                                  <li>
                                    <strong>Adittya Nath Mubayi – Quiz Expert</strong> – Decades of quizzing passion and expertise
                                    channelled into a programme that makes knowledge exciting for the next generation of Indian students.
                                  </li>
                                </ul>
                                <p>
                                  Together, these three pillars – institutional credibility, Ed-Tech excellence, and quizzing expertise –
                                  create a programme that is as trustworthy as it is transformative.
                                </p>
                            
                                <hr />
                            
                                <h3>The Impact on Students: Skills That Last a Lifetime</h3>
                                <p>
                                  Participation in a well-organised competition like CBCI Education MasterMinds gives students far more
                                  than a certificate. The real rewards are the skills, habits, and confidence they carry forward into
                                  every stage of life:
                                </p>
                                <ul>
                                  <li><strong>Stage confidence</strong> – Competing or performing before an audience builds presence and poise</li>
                                  <li><strong>Reading and research habits</strong> – Quiz preparation encourages students to stay curious and informed</li>
                                  <li><strong>Critical thinking</strong> – Questions on social justice and media push students to analyse, not just recall</li>
                                  <li><strong>Self-discovery</strong> – A child who discovers a talent for elocution here may build a career on that confidence later</li>
                                  <li><strong>National perspective</strong> – Competing alongside students from across India broadens horizons significantly</li>
                                </ul>
                                <p>
                                  Every year, students who participate in this programme walk away changed – more aware, more confident,
                                  and more connected to the world around them.
                                </p>
                            
                                <hr />
                            
                                <h3>How Schools Can Get Involved</h3>
                                <p>
                                  If you are a school principal, cultural coordinator, or faculty administrator looking to register for
                                  CBCI Education MasterMinds, the process is designed to be accessible and straightforward. Here is
                                  what you need to know:
                                </p>
                                <ul>
                                  <li>The programme is open to school students PAN India</li>
                                  <li>It runs in a hybrid format – online assessments, OMR-based tests, and live events</li>
                                  <li>Schools receive structured guidance on categories, age groups, and preparation</li>
                                  <li>The programme is held annually, anchored around Children's Day each year</li>
                                  <li>Coordination, logistics, and event execution support is available for participating institutions</li>
                                </ul>
                                <p>
                                  For schools planning their participation or the live event leg of the programme, working with an
                                  experienced event partner can make the entire process smoother – from stage setup and sound to crowd
                                  flow and ceremony management.
                                </p>
                            
